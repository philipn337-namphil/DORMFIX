CREATE TABLE maintenance_visit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_id BIGINT NOT NULL,
    worker_id BIGINT NOT NULL,
    created_by_id BIGINT NOT NULL,
    scheduled_start TIMESTAMPTZ NOT NULL,
    scheduled_end TIMESTAMPTZ NOT NULL,
    actual_started_at TIMESTAMPTZ,
    actual_ended_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL,
    entry_policy_snapshot VARCHAR(40) NOT NULL,
    contact_before_entry BOOLEAN NOT NULL,
    note VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_maintenance_visit PRIMARY KEY (id),
    CONSTRAINT fk_maintenance_visit_request FOREIGN KEY (request_id) REFERENCES maintenance_request (id) ON DELETE RESTRICT,
    CONSTRAINT fk_maintenance_visit_worker FOREIGN KEY (worker_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_maintenance_visit_created_by FOREIGN KEY (created_by_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_maintenance_visit_status CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELED', 'NO_ACCESS')),
    CONSTRAINT ck_maintenance_visit_entry_policy CHECK (entry_policy_snapshot IN ('RESIDENT_PRESENT_REQUIRED', 'ABSENT_ENTRY_ALLOWED')),
    CONSTRAINT ck_maintenance_visit_scheduled_order CHECK (scheduled_start < scheduled_end),
    CONSTRAINT ck_maintenance_visit_actual_order CHECK (actual_started_at IS NULL OR actual_ended_at IS NULL OR actual_started_at < actual_ended_at),
    -- Only complete writes the actual window, and it writes both halves. Any other status must
    -- therefore carry neither, which keeps NO_ACCESS and CANCELED from claiming a duration.
    CONSTRAINT ck_maintenance_visit_actual_status CHECK (
        (status = 'COMPLETED' AND actual_started_at IS NOT NULL AND actual_ended_at IS NOT NULL)
        OR (status <> 'COMPLETED' AND actual_started_at IS NULL AND actual_ended_at IS NULL))
);

-- A request has at most one open visit, so the three outcome commands are never ambiguous about
-- which attempt they describe. Mirrors ux_assignment_active_request.
CREATE UNIQUE INDEX ux_visit_open_request ON maintenance_visit (request_id) WHERE status = 'SCHEDULED';

CREATE INDEX ix_maintenance_visit_request_scheduled_start ON maintenance_visit (request_id, scheduled_start DESC);

CREATE INDEX ix_maintenance_visit_worker_scheduled_start ON maintenance_visit (worker_id, scheduled_start DESC);

ALTER TABLE request_history DROP CONSTRAINT ck_request_history_event_type;

ALTER TABLE request_history ADD CONSTRAINT ck_request_history_event_type CHECK (event_type IN (
    'REQUEST_CREATED',
    'REQUEST_ASSIGNED',
    'REQUEST_REASSIGNED',
    'REQUEST_STARTED',
    'REQUEST_HELD',
    'REQUEST_RESUMED',
    'REQUEST_RESOLVED',
    'REQUEST_CLOSED',
    'REQUEST_REOPENED',
    'REQUEST_REJECTED',
    'REQUEST_MARKED_DUPLICATE',
    'VISIT_SCHEDULED',
    'VISIT_RESCHEDULED',
    'VISIT_COMPLETED',
    'VISIT_CANCELED',
    'VISIT_NO_ACCESS'
));
