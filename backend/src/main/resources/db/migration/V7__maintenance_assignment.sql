CREATE TABLE maintenance_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_id BIGINT NOT NULL,
    worker_id BIGINT NOT NULL,
    assigned_by_id BIGINT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unassigned_at TIMESTAMPTZ,
    unassigned_by_id BIGINT,
    reason VARCHAR(500),
    CONSTRAINT pk_maintenance_assignment PRIMARY KEY (id),
    CONSTRAINT fk_maintenance_assignment_request FOREIGN KEY (request_id) REFERENCES maintenance_request (id) ON DELETE RESTRICT,
    CONSTRAINT fk_maintenance_assignment_worker FOREIGN KEY (worker_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_maintenance_assignment_assigned_by FOREIGN KEY (assigned_by_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_maintenance_assignment_unassigned_by FOREIGN KEY (unassigned_by_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_maintenance_assignment_unassigned CHECK ((unassigned_at IS NULL AND unassigned_by_id IS NULL) OR (unassigned_at IS NOT NULL AND unassigned_by_id IS NOT NULL)),
    CONSTRAINT ck_maintenance_assignment_unassigned_order CHECK (unassigned_at IS NULL OR assigned_at <= unassigned_at)
);

CREATE UNIQUE INDEX ux_assignment_active_request ON maintenance_assignment (request_id) WHERE unassigned_at IS NULL;

CREATE INDEX ix_maintenance_assignment_worker_assigned_at ON maintenance_assignment (worker_id, assigned_at DESC);

ALTER TABLE request_history DROP CONSTRAINT ck_request_history_event_type;

ALTER TABLE request_history ADD CONSTRAINT ck_request_history_event_type CHECK (event_type IN ('REQUEST_CREATED', 'REQUEST_ASSIGNED', 'REQUEST_REASSIGNED'));
