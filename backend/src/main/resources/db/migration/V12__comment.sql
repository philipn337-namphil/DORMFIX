CREATE TABLE comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    visibility VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT pk_comment PRIMARY KEY (id),
    CONSTRAINT fk_comment_request FOREIGN KEY (request_id) REFERENCES maintenance_request (id) ON DELETE RESTRICT,
    CONSTRAINT fk_comment_author FOREIGN KEY (author_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_comment_visibility CHECK (visibility IN ('PUBLIC', 'STAFF_ONLY')),
    CONSTRAINT ck_comment_deleted_after_created CHECK (deleted_at IS NULL OR created_at <= deleted_at)
);

CREATE INDEX ix_comment_request_created_at ON comment (request_id, created_at);

ALTER TABLE request_history DROP CONSTRAINT ck_request_history_event_type;

ALTER TABLE request_history ADD CONSTRAINT ck_request_history_event_type CHECK (event_type IN (
    'REQUEST_CREATED',
    'REQUEST_ASSIGNED',
    'REQUEST_REASSIGNED',
    'REQUEST_STARTED',
    'REQUEST_HELD',
    'REQUEST_RESUMED',
    'REQUEST_RESOLVED',
    'REQUEST_CLOSED',
    'REQUEST_REOPENED',
    'REQUEST_REJECTED',
    'REQUEST_MARKED_DUPLICATE',
    'VISIT_SCHEDULED',
    'VISIT_RESCHEDULED',
    'VISIT_COMPLETED',
    'VISIT_CANCELED',
    'VISIT_NO_ACCESS',
    'CATEGORY_CHANGED',
    'PRIORITY_CHANGED',
    'REQUEST_METADATA_UPDATED',
    'COMMENT_DELETED'
));
