CREATE TABLE work_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_id BIGINT NOT NULL,
    visit_id BIGINT,
    worker_id BIGINT NOT NULL,
    action_type VARCHAR(20) NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_work_log PRIMARY KEY (id),
    CONSTRAINT fk_work_log_request FOREIGN KEY (request_id) REFERENCES maintenance_request (id) ON DELETE RESTRICT,
    CONSTRAINT fk_work_log_visit FOREIGN KEY (visit_id) REFERENCES maintenance_visit (id) ON DELETE RESTRICT,
    CONSTRAINT fk_work_log_worker FOREIGN KEY (worker_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_work_log_action_type CHECK (action_type IN ('INSPECTION', 'REPAIR', 'REPLACEMENT', 'TEST', 'NOTE'))
);

-- A supplied visit must belong to the same request. That spans two rows, so the application
-- enforces it; the foreign key alone cannot.
CREATE INDEX ix_work_log_request_created_at ON work_log (request_id, created_at);

CREATE INDEX ix_work_log_visit ON work_log (visit_id);
