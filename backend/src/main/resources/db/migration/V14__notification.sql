CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    recipient_id BIGINT NOT NULL,
    request_id BIGINT,
    type VARCHAR(50) NOT NULL,
    title VARCHAR(150) NOT NULL,
    message VARCHAR(500) NOT NULL,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_notification PRIMARY KEY (id),
    CONSTRAINT fk_notification_recipient FOREIGN KEY (recipient_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_notification_request FOREIGN KEY (request_id) REFERENCES maintenance_request (id) ON DELETE RESTRICT,
    CONSTRAINT ck_notification_type CHECK (type IN (
        'REQUEST_SUBMITTED',
        'ASSIGNED_TO_YOU',
        'UNASSIGNED_FROM_YOU',
        'REQUEST_ASSIGNED',
        'REQUEST_STARTED',
        'REQUEST_HELD',
        'REQUEST_RESUMED',
        'REQUEST_RESOLVED',
        'REQUEST_CLOSED',
        'REQUEST_REOPENED',
        'REQUEST_REJECTED',
        'REQUEST_MARKED_DUPLICATE',
        'VISIT_SCHEDULED',
        'VISIT_RESCHEDULED',
        'VISIT_CANCELED',
        'VISIT_COMPLETED',
        'VISIT_NO_ACCESS',
        'COMMENT_ADDED'
    )),
    CONSTRAINT ck_notification_read_after_created CHECK (read_at IS NULL OR created_at <= read_at)
);

CREATE INDEX ix_notification_recipient_created ON notification (recipient_id, created_at DESC, id DESC);

CREATE INDEX ix_notification_recipient_unread ON notification (recipient_id) WHERE read_at IS NULL;
