CREATE TABLE attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_id BIGINT NOT NULL,
    uploader_id BIGINT NOT NULL,
    type VARCHAR(20) NOT NULL,
    object_key VARCHAR(500) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_attachment PRIMARY KEY (id),
    CONSTRAINT uq_attachment_object_key UNIQUE (object_key),
    CONSTRAINT fk_attachment_request FOREIGN KEY (request_id) REFERENCES maintenance_request (id) ON DELETE RESTRICT,
    CONSTRAINT fk_attachment_uploader FOREIGN KEY (uploader_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_attachment_type CHECK (type IN ('REPORT', 'BEFORE_REPAIR', 'AFTER_REPAIR', 'OTHER')),
    CONSTRAINT ck_attachment_file_size CHECK (file_size > 0)
);

CREATE INDEX ix_attachment_request_created_at ON attachment (request_id, created_at);
